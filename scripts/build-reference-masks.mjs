// Inspect the existing reference pixels and emit SVG clipping geometry.
// Source images are unchanged; no sky-colored rectangle is part of a sprite.
import sharp from 'sharp';
import { writeFile } from 'node:fs/promises';
const clouds = {
  day: [
    [272, 150, 281, 140],
    [1297, 239, 247, 125],
    [134, 348, 164, 75],
    [1195, 332, 88, 46],
    [1493, 430, 93, 45],
    [394, 459, 74, 38],
  ],
  night: [
    [277, 150, 276, 139],
    [1308, 244, 230, 115],
    [140, 345, 152, 72],
    [1496, 394, 88, 44],
  ],
};
const stars = [
  [88, 205, 13, 13],
  [148, 277, 5, 5],
  [449, 442, 6, 6],
  [563, 138, 5, 5],
  [625, 335, 13, 13],
  [778, 112, 13, 14],
  [841, 199, 5, 5],
  [1011, 297, 5, 5],
  [1121, 81, 6, 6],
  [1191, 352, 13, 14],
  [1338, 172, 7, 7],
  [1532, 68, 8, 8],
  [1607, 272, 6, 6],
];
const result = {};
for (const tone of ['day', 'night']) {
  const { data, info } = await sharp(`public/world/reference/${tone}.png`)
    .removeAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const pixel = (x, y) => {
    const i = (y * info.width + x) * 3;
    return [data[i], data[i + 1], data[i + 2]];
  };
  function mask([x, y, w, h], predicate, silhouette = false) {
    // Flood from the outside of the actual outline. A row's left/right span
    // would incorrectly fill the sky valleys between separate cloud lobes.
    const barrier = new Uint8Array(w * h),
      exterior = new Uint8Array(w * h);
    if (silhouette) {
      for (let row = 0; row < h; row++)
        for (let col = 0; col < w; col++)
          if (predicate(pixel(x + col, y + row))) {
            for (let dy = -1; dy <= 1; dy++)
              for (let dx = -1; dx <= 1; dx++) {
                const nx = col + dx,
                  ny = row + dy;
                if (nx >= 0 && nx < w && ny >= 0 && ny < h)
                  barrier[ny * w + nx] = 1;
              }
          }
      const queue = [];
      const visit = (col, row) => {
        if (col < 0 || col >= w || row < 0 || row >= h) return;
        const i = row * w + col;
        if (barrier[i] || exterior[i]) return;
        exterior[i] = 1;
        queue.push(i);
      };
      for (let col = 0; col < w; col++) {
        visit(col, 0);
        visit(col, h - 1);
      }
      for (let row = 0; row < h; row++) {
        visit(0, row);
        visit(w - 1, row);
      }
      for (let i = 0; i < queue.length; i++) {
        const col = queue[i] % w,
          row = Math.floor(queue[i] / w);
        visit(col - 1, row);
        visit(col + 1, row);
        visit(col, row - 1);
        visit(col, row + 1);
      }
    }
    const contains = (col, row) => {
      if (!silhouette) return predicate(pixel(col, row));
      // Remove the temporary one-pixel dilation used to seal outline pinholes.
      for (let dy = -1; dy <= 1; dy++)
        for (let dx = -1; dx <= 1; dx++) {
          const nx = col - x + dx,
            ny = row - y + dy;
          if (nx < 0 || nx >= w || ny < 0 || ny >= h || exterior[ny * w + nx])
            return false;
        }
      return true;
    };
    const runs = [];
    for (let row = y; row < y + h; row++) {
      const hits = [];
      for (let col = x; col < x + w; col++)
        if (contains(col, row)) hits.push(col);
      if (!hits.length) continue;
      {
        let start = hits[0],
          last = start;
        for (const col of hits.slice(1)) {
          if (col !== last + 1) {
            runs.push([start, row, last + 1, 1]);
            start = col;
          }
          last = col;
        }
        runs.push([start, row, last + 1, 1]);
      }
    }
    // Merge identical adjacent scanlines without changing any edge pixels.
    const merged = [];
    for (const run of runs) {
      const prev = merged.at(-1);
      if (
        prev &&
        prev[0] === run[0] &&
        prev[2] === run[2] &&
        prev[1] + prev[3] === run[1]
      )
        prev[3]++;
      else merged.push(run);
    }
    return merged
      .map(
        ([left, top, right, height]) =>
          `M${left} ${top}h${right - left}v${height}H${left}Z`,
      )
      .join('');
  }
  result[tone] = {
    clouds: clouds[tone].map((box) =>
      mask(
        box,
        ([r, g, b]) => (tone === 'day' ? b < 190 : r < 33 && g < 36 && b < 58),
        true,
      ),
    ),
    title: mask([30, 28, 285, 48], ([r, g, b]) =>
      tone === 'day'
        ? b < 155 && (r < 145 || r > g * 1.25)
        : (r > 155 && g > 155 && b > 155) || (r > 95 && r > g * 1.25),
    ),
    stars:
      tone === 'night'
        ? stars.map((box) =>
            mask(box, ([r, g, b]) => r > 85 && g > 95 && b > 100),
          )
        : [],
  };
}
await writeFile(
  'lib/reference-masks.ts',
  `// Generated by scripts/build-reference-masks.mjs from the unchanged reference artwork.\nexport const REFERENCE_MASKS = ${JSON.stringify(result, null, 2)} as const;\n`,
);
console.log(
  'Authored transparent SVG contours for ten clouds, both titles and thirteen stars.',
);
